#!/bin/bash

# Компиляция программы
echo "Компиляция..."
gcc shop_simulation.c -o shop_sim

# Функция для запуска теста и проверки ожидаемого вывода
run_test() {
    local test_name=$1
    local config_file=$2
    local expected_string=$3

    echo "----------------------------------------"
    echo "Запуск $test_name ($config_file)"

    # Запуск симуляции с передачей файла конфигурации
    output=$(./shop_sim "$config_file")

    # Поиск ожидаемого события в выводе
    if echo "$output" | grep -q "$expected_string"; then
        echo "✅ ПРОЙДЕН: Ожидаемое событие найдено ('$expected_string')"
    else
        echo "❌ ПРОВАЛЕН: Ожидаемое событие НЕ найдено ('$expected_string')"
        echo "Вывод программы:"
        echo "$output"
    fi
}

echo "=== Запуск автоматических тестов ==="

# Тест 0: Проверка на отсутствующий файл конфигурации (проверка обработки ошибок)
run_test "Тест 0: Ошибка чтения файла" "missing_config.txt" "Ошибка: не удалось открыть конфигурационный файл"

# Тест 1: Успешное завершение всех покупок
run_test "Тест 1: Обычный сценарий" "config_test1_normal.txt" "завершил список и покидает магазин"

# Тест 2: Покупатель приходит после закрытия
run_test "Тест 2: Закрытие дверей" "config_test2_late.txt" "пришел после закрытия и разворачивается"

# Тест 3: Формирование очереди
run_test "Тест 3: Конкуренция и очередь" "config_test3_queue.txt" "встает в очередь"

echo "----------------------------------------"
echo "Тестирование завершено. Логи последнего запуска можно посмотреть в sim_log.txt"